#!/usr/bin/env python3
"""Generate the Homebrew formula from the latest published stable CLI release."""
import argparse
import json
import os
from pathlib import Path
import re
from github import api
from package import sha256

REPO = "LioRael/lenso-cli"
TARGETS = {
    "macos": {"arm": "aarch64-apple-darwin", "intel": "x86_64-apple-darwin"},
    "linux": {"arm": "aarch64-unknown-linux-gnu", "intel": "x86_64-unknown-linux-gnu"},
}


def render(release, checksums):
    tag = release["tag_name"]
    if release["draft"] or release["prerelease"] or not re.fullmatch(r"v\d+\.\d+\.\d+", tag):
        raise ValueError("Homebrew requires a published stable CLI release")
    pins = {}
    for line in checksums.decode().splitlines():
        digest, name = line.split("  ", 1)
        if name in pins or not re.fullmatch(r"[a-f0-9]{64}", digest):
            raise ValueError("Invalid or duplicate release checksum")
        pins[name] = digest
    assets = {asset["name"]: asset for asset in release["assets"]}
    lines = [
        "# Generated by lenso-cli/scripts/release/homebrew.py.",
        "class Lenso < Formula",
        '  desc "Native CLI with composable Wasm extensions"',
        f'  homepage "https://github.com/{REPO}"',
        '  license any_of: ["MIT", "Apache-2.0"]',
    ]
    for system, targets in TARGETS.items():
        lines += ["", f"  on_{system} do"]
        if system == "macos":
            lines += ['    depends_on macos: :ventura', ""]
        for index, (arch, target) in enumerate(targets.items()):
            name = f"lenso-{tag}-{target}.tar.gz"
            asset = assets.get(name, {})
            digest = pins.get(name)
            if not digest or asset.get("state") != "uploaded" or asset.get("digest") != "sha256:" + digest:
                raise ValueError("Missing or conflicting published archive: " + name)
            if index:
                lines += [""]
            lines += [f"    on_{arch} do", f'      url "https://github.com/{REPO}/releases/download/{tag}/{name}"',
                      f'      sha256 "{digest}"', "    end"]
        lines += ["  end"]
    lines += ["", "  def install", '    bin.install "lenso"', "  end", "", "  test do",
              '    assert_equal "lenso #{version}", shell_output("#{bin}/lenso --version").strip',
              '    assert_match "self", shell_output("#{bin}/lenso --help")',
              '    report = JSON.parse(shell_output("#{bin}/lenso self update --check --offline --json"))',
              '    assert_equal "managed", report.fetch("outputs").fetch("main").fetch("state")',
              '    assert_match "brew upgrade", report.fetch("outputs").fetch("main").fetch("message")',
              "  end", "end", ""]
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--out", type=Path, required=True)
    args = parser.parse_args()
    release = api(REPO, "releases/latest")
    assets = [asset for asset in release["assets"] if asset["name"] == "SHA256SUMS"]
    if len(assets) != 1:
        raise ValueError("Expected one checksum manifest")
    asset = assets[0]
    checksums = api(REPO, "releases/assets/" + str(asset["id"]), binary=True)
    if asset.get("digest") != "sha256:" + sha256(checksums):
        raise ValueError("Checksum manifest differs from GitHub's asset digest")
    formula = render(release, checksums)
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(formula)
    if os.environ.get("GITHUB_OUTPUT"):
        with open(os.environ["GITHUB_OUTPUT"], "a") as stream:
            stream.write("version=" + release["tag_name"][1:] + "\n")
    print(json.dumps({"version": release["tag_name"][1:], "formula": str(args.out)}))


if __name__ == "__main__":
    main()
